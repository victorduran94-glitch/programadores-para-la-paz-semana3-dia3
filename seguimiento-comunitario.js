let semanasActuales = 1
const totalsemanas = 10

console.log("Revisión de las semanas de seguimiento comunitario")

while (semanasActuales <= totalsemanas) {
  console.log("Revisando semana número:", semanasActuales)
  semanasActuales = semanasActuales + 1
}

console.log("Proceso de revisión de semanas de seguimiento comunitario terminado.")
